create or replace function private.guard_report_context()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match_id uuid;
  v_user_low_id uuid;
  v_user_high_id uuid;
  v_message_sender_id uuid;
begin
  if new.message_id is not null then
    select m.match_id, m.sender_id
    into v_match_id, v_message_sender_id
    from public.messages m
    where m.id = new.message_id;

    if not found
      or v_message_sender_id <> new.reported_user_id
      or (new.match_id is not null and new.match_id <> v_match_id)
    then
      raise exception using
        errcode = '23514',
        message = 'reported message context is invalid';
    end if;

    new.match_id := v_match_id;
  end if;

  if new.match_id is not null then
    select m.user_low_id, m.user_high_id
    into v_user_low_id, v_user_high_id
    from public.matches m
    where m.id = new.match_id;

    if not found
      or new.reporter_id not in (v_user_low_id, v_user_high_id)
      or new.reported_user_id not in (v_user_low_id, v_user_high_id)
    then
      raise exception using
        errcode = '23514',
        message = 'reported match context is invalid';
    end if;
  end if;

  return new;
end;
$$;

create or replace function private.handle_block_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.likes
  set
    status = 'cancelled',
    resolved_at = statement_timestamp()
  where status = 'pending'
    and (
      (sender_id = new.blocker_id and recipient_id = new.blocked_id)
      or (sender_id = new.blocked_id and recipient_id = new.blocker_id)
    );

  update public.matches
  set
    status = 'blocked',
    ended_at = statement_timestamp()
  where status = 'active'
    and user_low_id = case
      when new.blocker_id::text < new.blocked_id::text then new.blocker_id
      else new.blocked_id
    end
    and user_high_id = case
      when new.blocker_id::text < new.blocked_id::text then new.blocked_id
      else new.blocker_id
    end;

  return new;
end;
$$;

