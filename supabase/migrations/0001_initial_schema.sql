create or replace function public.update_my_location(
  p_latitude double precision,
  p_longitude double precision,
  p_accuracy_m real default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_now timestamptz := statement_timestamp();
begin
  if v_user_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  if p_latitude not between -90 and 90
    or p_longitude not between -180 and 180
    or (p_accuracy_m is not null and p_accuracy_m not between 0 and 10000)
  then
    raise exception using errcode = '22023', message = 'invalid location';
  end if;

  if not exists (
    select 1
    from public.profiles
    where id = v_user_id
      and account_status = 'active'
  ) then
    raise exception using errcode = '42501', message = 'location update is not allowed';
  end if;

  insert into public.user_locations (
    user_id,
    location,
    accuracy_m,
    captured_at,
    expires_at
  )
  values (
    v_user_id,
    extensions.st_setsrid(
      extensions.st_makepoint(p_longitude, p_latitude),
      4326
    )::extensions.geography,
    p_accuracy_m,
    v_now,
    v_now + interval '15 minutes'
  )
  on conflict (user_id) do update
  set
    location = excluded.location,
    accuracy_m = excluded.accuracy_m,
    captured_at = excluded.captured_at,
    expires_at = excluded.expires_at;
end;
$$;

create or replace function public.activate_presence(
  p_mood public.mood,
  p_duration_minutes smallint default 60
)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_now timestamptz := statement_timestamp();
  v_available_until timestamptz;
begin
  if v_user_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  if p_duration_minutes not between 15 and 240 then
    raise exception using errcode = '22023', message = 'availability duration must be between 15 and 240 minutes';
  end if;

  if not exists (
    select 1
    from public.profiles
    where id = v_user_id
      and account_status = 'active'
      and is_profile_complete
  ) or not exists (
    select 1
    from public.user_locations
    where user_id = v_user_id
      and expires_at > v_now
  ) then
    raise exception using errcode = '42501', message = 'presence activation is not allowed';
  end if;

  v_available_until := v_now + make_interval(mins => p_duration_minutes);

  insert into public.user_presence (
    user_id,
    availability_status,
    mood,
    last_heartbeat_at,
    activated_at,
    available_until
  )
  values (
    v_user_id,
    'available',
    p_mood,
    v_now,
    v_now,
    v_available_until
  )
  on conflict (user_id) do update
  set
    availability_status = 'available',
    mood = excluded.mood,
    last_heartbeat_at = excluded.last_heartbeat_at,
    activated_at = excluded.activated_at,
    available_until = excluded.available_until;

  return v_available_until;
end;
$$;

create or replace function public.heartbeat_presence()
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_available_until timestamptz;
begin
  if v_user_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  update public.user_presence
  set last_heartbeat_at = statement_timestamp()
  where user_id = v_user_id
    and availability_status = 'available'
    and available_until > statement_timestamp()
  returning available_until into v_available_until;

  if v_available_until is null then
    raise exception using errcode = '55000', message = 'presence is not active';
  end if;

  return v_available_until;
end;
$$;

create or replace function public.deactivate_presence(p_hidden boolean default false)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  insert into public.user_presence (user_id, availability_status)
  values (
    v_user_id,
    case when p_hidden then 'hidden'::public.availability_status else 'offline'::public.availability_status end
  )
  on conflict (user_id) do update
  set
    availability_status = excluded.availability_status,
    mood = null,
    last_heartbeat_at = statement_timestamp(),
    activated_at = null,
    available_until = null;

  delete from public.user_locations where user_id = v_user_id;
end;
$$;

create or replace function public.get_nearby_profiles(
  p_radius_m integer default 5000,
  p_limit integer default 20
)
returns table (
  profile_id uuid,
  first_name text,
  age smallint,
  bio text,
  gender public.gender,
  mood public.mood,
  distance_band public.distance_band,
  primary_photo_url text,
  interest_slugs text[]
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  if p_radius_m <> all (array[1000, 3000, 5000, 10000])
    or p_limit not between 1 and 50
  then
    raise exception using errcode = '22023', message = 'invalid discovery parameters';
  end if;

  return query
  with me as (
    select
      l.location,
      p.gender,
      p.searching_for
    from public.user_locations l
    join public.profiles p on p.id = l.user_id
    where l.user_id = v_user_id
      and l.expires_at > statement_timestamp()
      and p.account_status = 'active'
  ),
  candidates as (
    select
      p.id,
      p.first_name,
      extract(year from age(current_date, p.birth_date))::smallint as public_age,
      p.bio,
      p.gender,
      pr.mood,
      extensions.st_distance(l.location, me.location) as distance_m
    from me
    join public.user_locations l
      on extensions.st_dwithin(l.location, me.location, p_radius_m)
    join public.profiles p on p.id = l.user_id
    join public.user_presence pr on pr.user_id = p.id
    where p.id <> v_user_id
      and l.expires_at > statement_timestamp()
      and p.account_status = 'active'
      and p.is_discoverable
      and p.is_profile_complete
      and p.birth_date is not null
      and p.gender is not null
      and p.gender = any (me.searching_for)
      and me.gender = any (p.searching_for)
      and pr.availability_status = 'available'
      and pr.available_until > statement_timestamp()
      and pr.last_heartbeat_at >= statement_timestamp() - interval '5 minutes'
      and not exists (
        select 1
        from public.blocks b
        where (b.blocker_id = v_user_id and b.blocked_id = p.id)
           or (b.blocker_id = p.id and b.blocked_id = v_user_id)
      )
  )
  select
    c.id,
    c.first_name,
    c.public_age,
    c.bio,
    c.gender,
    c.mood,
    case
      when c.distance_m < 150 then 'TOUT_PRES'::public.distance_band
      when c.distance_m < 500 then 'MOINS_DE_500_M'::public.distance_band
      when c.distance_m < 1000 then 'ENTRE_500_M_ET_1_KM'::public.distance_band
      else 'DANS_TON_SECTEUR'::public.distance_band
    end,
    photo.secure_url,
    coalesce(interests.slugs, '{}'::text[])
  from candidates c
  left join lateral (
    select pp.secure_url
    from public.profile_photos pp
    where pp.profile_id = c.id
      and pp.deleted_at is null
    order by pp.sort_order
    limit 1
  ) photo on true
  left join lateral (
    select array_agg(i.slug order by i.slug) as slugs
    from public.user_interests ui
    join public.interests i on i.id = ui.interest_id
    where ui.user_id = c.id
      and i.is_active
  ) interests on true
  order by md5(
    c.id::text
    || v_user_id::text
    || floor(extract(epoch from statement_timestamp()) / 900)::text
  )
  limit p_limit;
end;
$$;

create or replace function public.send_hello(p_recipient_id uuid)
returns table (
  like_id uuid,
  match_id uuid,
  is_match boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sender_id uuid := auth.uid();
  v_like_id uuid;
  v_reciprocal_like_id uuid;
  v_match_id uuid;
  v_user_low_id uuid;
  v_user_high_id uuid;
  v_daily_limit integer := 25;
begin
  if v_sender_id is null then
    raise exception using errcode = '28000', message = 'authentication required';
  end if;

  if p_recipient_id is null or p_recipient_id = v_sender_id then
    raise exception using errcode = '22023', message = 'invalid recipient';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      least(v_sender_id::text, p_recipient_id::text)
      || ':'
      || greatest(v_sender_id::text, p_recipient_id::text),
      0
    )
  );

  if not exists (
    select 1
    from public.profiles
    where id = v_sender_id
      and account_status = 'active'
      and is_profile_complete
  ) or not exists (
    select 1
    from public.user_presence
    where user_id = v_sender_id
      and availability_status = 'available'
      and available_until > statement_timestamp()
      and last_heartbeat_at >= statement_timestamp() - interval '5 minutes'
  ) or not exists (
    select 1
    from public.profiles
    where id = p_recipient_id
      and account_status = 'active'
      and is_profile_complete
  ) or not exists (
    select 1
    from public.user_presence
    where user_id = p_recipient_id
      and availability_status = 'available'
      and available_until > statement_timestamp()
      and last_heartbeat_at >= statement_timestamp() - interval '5 minutes'
  ) then
    raise exception using errcode = '42501', message = 'hello request is not allowed';
  end if;

  if exists (
    select 1
    from public.blocks
    where (blocker_id = v_sender_id and blocked_id = p_recipient_id)
       or (blocker_id = p_recipient_id and blocked_id = v_sender_id)
  ) then
    raise exception using errcode = '42501', message = 'hello request is not allowed';
  end if;

  if exists (
    select 1
    from public.likes
    where sender_id = v_sender_id
      and recipient_id = p_recipient_id
      and status = 'pending'
  ) then
    raise exception using errcode = '23505', message = 'a hello request is already pending';
  end if;

  if (
    select count(*)
    from public.likes
    where sender_id = v_sender_id
      and created_at >= statement_timestamp() - interval '1 hour'
  ) >= 5 then
    raise exception using errcode = '54000', message = 'hourly hello limit reached';
  end if;

  select coalesce((value #>> '{}')::integer, 25)
  into v_daily_limit
  from private.app_settings
  where key = 'hello_daily_limit';

  v_daily_limit := coalesce(v_daily_limit, 25);

  if (
    select count(*)
    from public.likes
    where sender_id = v_sender_id
      and created_at >= date_trunc('day', statement_timestamp())
  ) >= v_daily_limit then
    raise exception using errcode = '54000', message = 'daily hello limit reached';
  end if;

  insert into public.likes (sender_id, recipient_id)
  values (v_sender_id, p_recipient_id)
  returning id into v_like_id;

  select id
  into v_reciprocal_like_id
  from public.likes
  where sender_id = p_recipient_id
    and recipient_id = v_sender_id
    and status = 'pending'
  order by created_at desc
  limit 1
  for update;

  if v_reciprocal_like_id is null then
    return query select v_like_id, null::uuid, false;
    return;
  end if;

  if v_sender_id::text < p_recipient_id::text then
    v_user_low_id := v_sender_id;
    v_user_high_id := p_recipient_id;
  else
    v_user_low_id := p_recipient_id;
    v_user_high_id := v_sender_id;
  end if;

  insert into public.matches (user_low_id, user_high_id)
  values (v_user_low_id, v_user_high_id)
  on conflict (user_low_id, user_high_id) do update
  set
    status = 'active',
    matched_at = statement_timestamp(),
    ended_at = null
  returning id into v_match_id;

  update public.likes
  set
    status = 'matched',
    matched_at = statement_timestamp()
  where id in (v_like_id, v_reciprocal_like_id);

  return query select v_like_id, v_match_id, true;
end;
$$;

create or replace function public.expire_stale_presence()
returns table (
  presences_expired integer,
  locations_deleted integer
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_presences integer;
  v_locations integer;
begin
  update public.user_presence
  set
    availability_status = 'offline',
    mood = null,
    activated_at = null,
    available_until = null
  where availability_status = 'available'
    and (
      available_until <= statement_timestamp()
      or last_heartbeat_at < statement_timestamp() - interval '5 minutes'
    );

  get diagnostics v_presences = row_count;

  delete from public.user_locations
  where expires_at <= statement_timestamp();

  get diagnostics v_locations = row_count;
  return query select v_presences, v_locations;
end;
$$;

