create table public.profiles (
  id uuid primary key references auth.users (id) on delete restrict,
  first_name text,
  birth_date date,
  gender public.gender,
  searching_for public.gender[] not null default '{}'::public.gender[],
  bio text,
  account_status public.account_status not null default 'active',
  is_discoverable boolean not null default true,
  is_profile_complete boolean not null default false,
  suspended_until timestamptz,
  deletion_requested_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_first_name_length
    check (first_name is null or char_length(btrim(first_name)) between 1 and 50),
  constraint profiles_bio_length
    check (bio is null or char_length(bio) <= 150),
  constraint profiles_searching_for_limit
    check (cardinality(searching_for) <= 5),
  constraint profiles_suspension_consistency
    check (account_status = 'suspended' or suspended_until is null),
  constraint profiles_deletion_consistency
    check (
      (account_status = 'pending_deletion' and deletion_requested_at is not null)
      or (account_status <> 'pending_deletion' and deletion_requested_at is null)
    )
);

