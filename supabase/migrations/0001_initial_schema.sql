create or replace function private.enforce_active_photo_limit()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_count integer;
begin
  if new.deleted_at is not null then
    return new;
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('profile_photos:' || new.profile_id::text, 0)
  );

  select count(*)::integer
  into v_count
  from public.profile_photos
  where profile_id = new.profile_id
    and deleted_at is null
    and id <> new.id;

  if v_count >= 4 then
    raise exception using
      errcode = '23514',
      message = 'a profile can have at most four active photos';
  end if;

  return new;
end;
$$;

