create or replace function private.guard_message_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match public.matches%rowtype;
  v_duplicate_count integer;
  v_content_hash bytea;
begin
  select *
  into v_match
  from public.matches
  where id = new.match_id
  for share;

  if not found
    or new.sender_id not in (v_match.user_low_id, v_match.user_high_id)
    or v_match.status <> 'active'
  then
    raise exception using
      errcode = '42501',
      message = 'message is not allowed';
  end if;

  if exists (
    select 1
    from public.blocks
    where (blocker_id = v_match.user_low_id and blocked_id = v_match.user_high_id)
       or (blocker_id = v_match.user_high_id and blocked_id = v_match.user_low_id)
  ) then
    raise exception using
      errcode = '42501',
      message = 'message is not allowed';
  end if;

  if not exists (
    select 1
    from public.profiles
    where id = new.sender_id
      and account_status = 'active'
  ) then
    raise exception using
      errcode = '42501',
      message = 'message is not allowed';
  end if;

  new.content := btrim(new.content);
  v_content_hash := extensions.digest(
    lower(regexp_replace(new.content, '\s+', ' ', 'g')),
    'sha256'
  );

  select count(*)::integer
  into v_duplicate_count
  from public.messages
  where sender_id = new.sender_id
    and content_hash = v_content_hash
    and created_at >= statement_timestamp() - interval '1 hour';

  if v_duplicate_count >= 5 then
    raise exception using
      errcode = '54000',
      message = 'repeated message limit reached';
  end if;

  return new;
end;
$$;

create or replace function private.guard_message_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.match_id <> old.match_id
    or new.sender_id <> old.sender_id
    or new.content <> old.content
    or new.created_at <> old.created_at
  then
    raise exception using
      errcode = '55000',
      message = 'message content and ownership are immutable';
  end if;

  return new;
end;
$$;

