create or replace function private.refresh_profile_from_child()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    perform private.refresh_profile_completion(old.profile_id);
  else
    perform private.refresh_profile_completion(new.profile_id);
    if tg_op = 'UPDATE' and old.profile_id <> new.profile_id then
      perform private.refresh_profile_completion(old.profile_id);
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

