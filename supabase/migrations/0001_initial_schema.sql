create or replace function private.validate_profile_age()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.birth_date is not null then
    if new.birth_date > current_date - interval '18 years' then
      raise exception using
        errcode = '22023',
        message = 'profile owner must be at least 18 years old';
    end if;

    if new.birth_date < current_date - interval '100 years' then
      raise exception using
        errcode = '22023',
        message = 'birth date is outside the accepted range';
    end if;
  end if;

  new.first_name := nullif(btrim(new.first_name), '');
  new.bio := nullif(btrim(new.bio), '');
  return new;
end;
$$;

